var defaultLanguage = "en"

function isLanguage(value) {
  return Object.prototype.hasOwnProperty.call(translations, value)
}

// Supported language of a locale identifier such as "es-ES", "ca_ES.UTF-8" or
// "fr", English when it is not supported
function normalize(identifier) {
  var language = String(identifier || "").trim().toLowerCase()
  var match = language.search(/[-_.@]/)
  if (match >= 0) language = language.substring(0, match)
  return isLanguage(language) ? language : defaultLanguage
}

function isEnglish(identifier) {
  var language = String(identifier || "").trim().toLowerCase()
  return language === "en" || language.indexOf("en-") === 0 || language.indexOf("en_") === 0
}

// First supported language of locale identifiers ordered by preference
function fromPreferences(identifiers) {
  for (var i = 0; i < identifiers.length; i++) {
    var language = normalize(identifiers[i])
    if (language !== defaultLanguage || isEnglish(identifiers[i])) return language
  }
  return defaultLanguage
}

// POSIX precedence: LANGUAGE (a list separated by colons), LC_ALL,
// LC_MESSAGES, LANG
function systemLanguage(env) {
  var preferences = []
  var list = env("LANGUAGE")
  if (list) preferences = preferences.concat(String(list).split(":"))
  var variables = ["LC_ALL", "LC_MESSAGES", "LANG"]
  for (var i = 0; i < variables.length; i++) {
    var value = env(variables[i])
    if (value) preferences.push(String(value))
  }
  return fromPreferences(preferences)
}

